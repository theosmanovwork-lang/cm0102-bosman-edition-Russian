#!/usr/bin/env python3
"""Validate the Russian localisation TSV and generate T2K-safe C strings.

The original game accepts #XXXX# Unicode escapes in its text renderer. The
source catalogue stays UTF-8 for translators; the generated C header contains
ASCII-only escapes so no Windows-1252 conversion can corrupt Cyrillic.
"""
from __future__ import annotations

import argparse
import csv
import re
from pathlib import Path

PRINTF = re.compile(
    r"%(?:(\d+)\$)?([-+#0 ']*)(?:\*(?:\d+\$)?|\d+)?"
    r"(?:\.(?:\*(?:\d+\$)?|\d*))?"
    r"(hh|h|ll|l|z|j|t|L|I64)?([diuoxXfFeEgGaAcCsSpn])"
)
MARKUP = re.compile(r"\{[^{}]*\}|\[[^\[\]]*\]")


def printf_signature(value: str) -> tuple[tuple[str, str], ...]:
    result: list[tuple[str, str]] = []
    pos = 0
    while pos < len(value):
        if value[pos] != "%":
            pos += 1
            continue
        if pos + 1 < len(value) and value[pos + 1] == "%":
            pos += 2
            continue
        match = PRINTF.match(value, pos)
        if not match:
            raise ValueError(f"invalid printf placeholder at offset {pos}: {value!r}")
        position, _flags, _width_length, specifier = match.groups()
        result.append((position or "", specifier))
        pos = match.end()
    return tuple(result)


def encode_t2k(value: str) -> str:
    out: list[str] = []
    for char in value:
        code = ord(char)
        if code > 0xFFFF:
            raise ValueError(
                f"character U+{code:06X} is outside the game's four-digit #XXXX# escape range"
            )
        out.append(f"#{code:04X}#" if code > 0x7F else char)
    return "".join(out)


def c_string(value: str) -> str:
    escaped = value.replace("\\", "\\\\").replace('"', '\\\"')
    escaped = escaped.replace("\n", "\\n").replace("\r", "\\r").replace("\t", "\\t")
    return '"' + escaped + '"'


def read_catalog(path: Path) -> list[dict[str, str]]:
    with path.open("r", encoding="utf-8-sig", newline="") as stream:
        rows = list(csv.DictReader(stream, delimiter="\t"))
    required = {"id", "source", "translation", "context"}
    if not rows or not required.issubset(rows[0]):
        raise ValueError("TSV header must contain id, source, translation and context")

    seen_ids: set[str] = set()
    seen_sources: set[str] = set()
    for row in rows:
        if not row["id"].strip() or not row["source"] or not row["translation"]:
            raise ValueError("every row needs a non-empty id, source and translation")
        if row["id"] in seen_ids:
            raise ValueError(f"duplicate id: {row['id']}")
        if row["source"] in seen_sources:
            raise ValueError(f"duplicate source string: {row['source']!r}")
        seen_ids.add(row["id"])
        seen_sources.add(row["source"])

        if printf_signature(row["source"]) != printf_signature(row["translation"]):
            raise ValueError(f"printf placeholders differ for {row['id']}")
        if MARKUP.findall(row["source"]) != MARKUP.findall(row["translation"]):
            if MARKUP.findall(row["source"]) or MARKUP.findall(row["translation"]):
                raise ValueError(f"game markup differs for {row['id']}")
        encode_t2k(row["translation"])
    return rows


def render_header(rows: list[dict[str, str]]) -> str:
    body = "\n".join(
        f"    {{{c_string(row['source'])}, {c_string(encode_t2k(row['translation']))}}},"
        for row in rows
    )
    return (
        "/* Generated by tools/localisation/build_catalog.py from locales/ru-RU.tsv. Do not edit by hand. */\n"
        "#ifndef CM0102_RUSSIAN_CATALOG_H\n#define CM0102_RUSSIAN_CATALOG_H\n\n"
        "typedef struct { const char *source; const char *target; } LocalisationEntry;\n"
        "static const LocalisationEntry russian_catalog[] = {\n"
        f"{body}\n"
        "};\n#define RUSSIAN_CATALOG_COUNT (sizeof russian_catalog / sizeof russian_catalog[0])\n\n"
        "#endif\n"
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("catalog", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    rows = read_catalog(args.catalog)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(render_header(rows), encoding="ascii", newline="\n")
    print(f"{len(rows)} Russian entries: {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
